//! `remote-agent share` — bootstrap a fresh host into this room with one paste.
//!
//! Generates a self-contained `sh` (Linux/macOS) or `ps1` (Windows) script that:
//!   1. detects the platform/arch,
//!   2. downloads the latest `remote-agent` binary straight from the GitHub
//!      release (no npm, no cargo, no dependencies beyond curl/Expand-Archive),
//!   3. embeds the *current* connection config (room, token, relay, name
//!      prefix, tags, encryption key) as base64 JSON,
//!   4. runs `remote-agent run --bootstrap <b64>` — the binary sees the flag,
//!      decodes the config, overrides/ignores any local config file, and joins
//!      the room immediately.
//!
//! The use case: quickly handing room credentials to a remote host that has
//! nothing installed — paste one line, get a live agent.
//!
//! Security note: the script carries the room token in plain (base64) text —
//! base64 is encoding, NOT encryption. Treat the generated script like a
//! password; the room token is the only gate (token-addressed rooms).
//! `share` redacts nothing on purpose: the whole point is a working paste.

use anyhow::{Context, Result};
use base64::Engine as _;
use crate::config::Config;

/// The GitHub repo that carries the release binaries (matches npm/install.js).
pub const REPO: &str = "47-ronn/remote-agents-mcp";

/// A portable subset of the config the bootstrap carries. `id` is deliberately
/// NOT carried (the new host generates its own); `name` comes through as a
/// *hint* only when the sharer set a non-default name — two hosts with the
/// same explicit name would be confusing, so the script drops it when it just
/// mirrors the hostname default.
#[derive(serde::Serialize, serde::Deserialize, Default)]
pub struct BootstrapConfig {
    pub room: String,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub token: String,
    pub relay_url: String,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub name: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tags: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub encryption_key: Option<String>,
    #[serde(default)]
    pub accepts_commands: bool,
}

impl BootstrapConfig {
    /// Extract the shareable subset from the host's effective config.
    pub fn from_config(cfg: &Config) -> Self {
        Self {
            room: cfg.room.clone(),
            token: cfg.token.clone(),
            relay_url: cfg.relay_url.clone(),
            name: cfg.name.clone(),
            tags: cfg.tags.clone(),
            encryption_key: cfg.security.encryption_key.clone(),
            accepts_commands: cfg.accepts_commands,
        }
    }

    pub fn to_b64(&self) -> String {
        base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(
            serde_json::to_vec(self).expect("bootstrap config serializes"),
        )
    }

    pub fn from_b64(s: &str) -> Result<Self> {
        let bytes = base64::engine::general_purpose::URL_SAFE_NO_PAD
            .decode(s.trim())
            .context("bootstrap config: invalid base64")?;
        serde_json::from_slice(&bytes).context("bootstrap config: invalid JSON")
    }

    /// Apply the bootstrap as CLI-level overrides on top of a local/default
    /// config: bootstrap WINS over the config file (the sharer's room is the
    /// point), except for fields the bootstrap left empty.
    pub fn apply_over(self, cfg: &mut Config) {
        cfg.room = self.room;
        cfg.relay_url = self.relay_url;
        if !self.token.is_empty() {
            cfg.token = self.token;
        }
        if !self.name.is_empty() {
            cfg.name = self.name;
        }
        if !self.tags.is_empty() {
            cfg.tags = self.tags;
        }
        if self.encryption_key.is_some() {
            cfg.security.encryption_key = self.encryption_key;
        }
        cfg.accepts_commands = self.accepts_commands;
    }
}

/// POSIX `sh` bootstrap: downloads the latest release binary for the detected
/// arch, decodes the embedded config to a file, and execs the agent.
/// Works on Linux (musl static) and macOS, bash or dash, no dependencies
/// beyond `curl` (present basically everywhere).
pub fn sh_script(b64: &str) -> String {
    format!(
        r#"#!/bin/sh
# remote-agent bootstrap — generated by `remote-agent share`.
# Paste on the target host; it downloads the latest release binary from
# github.com/{repo} and joins the room with the embedded config.
set -eu
os="$(uname -s)"; arch="$(uname -m)"
case "$os:$arch" in
  Linux:x86_64)  target=x86_64-unknown-linux-musl ;;
  Linux:aarch64) target=aarch64-unknown-linux-musl ;;
  Darwin:x86_64) target=x86_64-apple-darwin ;;
  Darwin:arm64)  target=aarch64-apple-darwin ;;
  *) echo "unsupported platform: $os $arch" >&2; exit 1 ;;
esac
dir="${{TMPDIR:-/tmp}}/remote-agent-bootstrap"
mkdir -p "$dir"
bin="$dir/remote-agent"
url="https://github.com/{repo}/releases/latest/download/remote-agent-$target"
echo "downloading $url …"
curl -fsSL --retry 3 -o "$bin" "$url"
chmod +x "$bin"
# --bootstrap <b64>: room/token/relay/tags ride along (base64 JSON).
exec "$bin" run --bootstrap '{b64}'"#
    ,
        repo = REPO,
        b64 = b64,
    )
}

/// Windows `ps1` bootstrap: same flow via Invoke-WebRequest, base64 config to
/// file, then run. `Expand-Archive` is not needed — the raw single binary is
/// downloaded directly.
pub fn ps1_script(b64: &str) -> String {
    format!(
        r#"# remote-agent bootstrap — generated by `remote-agent share`.
# Run on the target Windows host (unblock first if downloaded:
#   Unblock-File .\bootstrap.ps1 ; powershell -ExecutionPolicy Bypass -File .\bootstrap.ps1)
$ErrorActionPreference = 'Stop'
$arch = $env:PROCESSOR_ARCHITECTURE
if ($arch -eq 'AMD64') {{ $target = 'x86_64-pc-windows-msvc.exe' }}
elseif ($arch -eq 'ARM64') {{ $target = 'aarch64-unknown-linux-musl' }} # Windows-on-ARM: no MSVC asset yet
else {{ throw "unsupported architecture: $arch" }}
$dir = Join-Path $env:TEMP 'remote-agent-bootstrap'
New-Item -ItemType Directory -Force -Path $dir | Out-Null
$bin = Join-Path $dir 'remote-agent.exe'
$url = "https://github.com/{repo}/releases/latest/download/remote-agent-$target"
Write-Host "downloading $url ..."
Invoke-WebRequest -Uri $url -OutFile $bin -UseBasicParsing
# --bootstrap <b64>: room/token/relay/tags ride along (base64 JSON).
& $bin run --bootstrap '{b64}'"#
    ,
        repo = REPO,
        b64 = b64,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> Config {
        let mut c = Config {
            room: "gpu".into(),
            token: "sekrit".into(),
            relay_url: "wss://relay.example/".into(),
            name: "htf".into(),
            tags: vec!["gpu".into(), "vm".into()],
            ..Default::default()
        };
        c.security.encryption_key = Some("k".into());
        c
    }

    #[test]
    fn bootstrap_roundtrips_through_base64() {
        let b = BootstrapConfig::from_config(&cfg());
        let b2 = BootstrapConfig::from_b64(&b.to_b64()).unwrap();
        assert_eq!(b2.room, "gpu");
        assert_eq!(b2.token, "sekrit");
        assert_eq!(b2.relay_url, "wss://relay.example/");
        assert_eq!(b2.tags, vec!["gpu".to_string(), "vm".to_string()]);
        assert_eq!(b2.encryption_key.as_deref(), Some("k"));
        assert!(b2.accepts_commands);
    }

    #[test]
    fn apply_over_bootstrap_wins() {
        let mut local = Config {
            room: "old-room".into(),
            token: "local-token".into(),
            tags: vec!["local".into()],
            ..Default::default()
        };
        BootstrapConfig::from_config(&cfg()).apply_over(&mut local);
        assert_eq!(local.room, "gpu");
        assert_eq!(local.relay_url, "wss://relay.example/");
        assert_eq!(local.tags, vec!["gpu".to_string(), "vm".to_string()]);
        // name carried (explicit, non-default)
        assert_eq!(local.name, "htf");
    }

    #[test]
    fn empty_bootstrap_token_keeps_local() {
        let mut c = cfg();
        c.token = String::new();
        let mut local = Config {
            token: "local-token".into(),
            ..Default::default()
        };
        BootstrapConfig::from_config(&c).apply_over(&mut local);
        assert_eq!(local.token, "local-token");
        assert_eq!(local.room, "gpu"); // room still wins (never empty)
    }

    #[test]
    fn scripts_embed_b64_and_download_latest() {
        let b64 = BootstrapConfig::from_config(&cfg()).to_b64();
        let sh = sh_script(&b64);
        let ps1 = ps1_script(&b64);
        for s in [&sh, &ps1] {
            assert!(s.contains(&b64), "script must embed the b64 config");
            assert!(s.contains("releases/latest/download"), "must download latest");
            assert!(s.contains("--bootstrap"));
        }
        // sh covers the four unix targets; ps1 covers amd64.
        assert!(sh.contains("x86_64-unknown-linux-musl"));
        assert!(sh.contains("aarch64-unknown-linux-musl"));
        assert!(sh.contains("x86_64-apple-darwin"));
        assert!(sh.contains("aarch64-apple-darwin"));
        assert!(ps1.contains("x86_64-pc-windows-msvc"));
    }

    #[test]
    fn malformed_b64_is_a_typed_error_not_a_panic() {
        assert!(BootstrapConfig::from_b64("!!!not-base64").is_err());
        assert!(BootstrapConfig::from_b64("aGVsbG8").is_err()); // valid b64, not JSON
    }
}